'use strict';

/**
 * Generates src/web/public/demo-data.js — an embedded dataset that lets the
 * front-end render a meaningful timeline on static hosts (e.g. GitHub Pages)
 * where the Node/Express backend is not available.
 *
 * Run: node tools/generate-demo.js
 */

const fs = require('node:fs');
const path = require('node:path');

const { Repo } = require('../src/core/repo');
const { buildTimeline } = require('../src/core/timeline');
const { gatherCommitEvidence } = require('../src/core/evidence');
const { buildScenario } = require('../test/helpers');

async function main() {
  const scenario = buildScenario();
  const repo = await Repo.open(scenario.root);

  const timeline = await buildTimeline(repo, { all: true });

  const commits = {};
  for (const c of timeline.commits) {
    try {
      commits[c.sha] = await gatherCommitEvidence(repo, c.sha);
    } catch (err) {
      process.stderr.write(`skip ${c.short}: ${err.message}\n`);
    }
  }

  const demo = {
    generatedAt: new Date().toISOString(),
    repo: {
      name: 'sample-project',
      branch: timeline.repository.branch,
      defaultBranch: timeline.repository.defaultBranch,
      headSha: timeline.repository.headSha,
      branchCount: timeline.refs.branches.length,
      tagCount: timeline.refs.tags.length,
      ai: { enabled: false, provider: null, model: null, host: null },
    },
    timeline,
    commits,
  };

  const out =
    '/* Generated by tools/generate-demo.js. Do not edit by hand. */\n' +
    'window.GIT_REPLAY_DEMO =\n' +
    JSON.stringify(demo, null, 1) +
    ';\n';

  const target = path.join(__dirname, '..', 'src', 'web', 'public', 'demo-data.js');
  fs.writeFileSync(target, out, 'utf8');

  scenario.cleanup();
  process.stdout.write(
    `wrote ${target} (${out.length} bytes) · ${timeline.commits.length} commits · ` +
      `${Object.keys(commits).length} with detail\n`
  );
}

main().catch((err) => {
  process.stderr.write(String(err && err.stack ? err.stack : err) + '\n');
  process.exit(1);
});